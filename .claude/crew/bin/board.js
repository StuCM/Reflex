#!/usr/bin/env node
// Renders .claude/tasks/BOARD.md from the task files' frontmatter.
//
// The board is derived, never hand-maintained: task files are the single
// source of truth, so a session that updates its own task cannot leave the
// board saying something else. Run it after any status change.
'use strict';

var fs = require('fs');
var path = require('path');
var execSync = require('child_process').execSync;

var root = path.resolve(__dirname, '..', '..', '..');
var dir = path.join(root, '.claude', 'tasks');

var ORDER = ['blocked', 'pending-tv', 'draft', 'review', 'building', 'approved', 'done'];

var tasks = fs.readdirSync(dir)
  .filter(function (f) { return /^\d{3}-.*\.md$/.test(f); })
  .map(function (f) {
    var text = fs.readFileSync(path.join(dir, f), 'utf8');
    return {
      file: f,
      id: field(text, 'id') || f.slice(0, 3),
      status: field(text, 'status') || '?',
      env: field(text, 'env') || '?',
      branch: field(text, 'branch') || '',
      model: field(text, 'model') || '',
      title: title(text) || f
    };
  })
  .sort(function (a, b) {
    var d = ORDER.indexOf(a.status) - ORDER.indexOf(b.status);
    return d !== 0 ? d : a.id.localeCompare(b.id);
  });

var live = branches();

var out = [];
out.push('# Board');
out.push('');
out.push('Generated by `node .claude/crew/bin/board.js` — do not edit by hand.');
out.push('Task files are the source of truth; this is the glance view.');
out.push('');
out.push('| id | task | status | env | branch |');
out.push('|---|---|---|---|---|');

tasks.forEach(function (t) {
  var b = t.branch ? (live.indexOf(t.branch) === -1 ? t.branch + ' *(gone)*' : t.branch) : '—';
  out.push('| ' + t.id + ' | ' + t.title + ' | `' + t.status + '` | ' + t.env + ' | ' + b + ' |');
});

if (!tasks.length) out.push('| — | *no tasks yet* | | | |');

var waiting = tasks.filter(function (t) {
  return t.status === 'draft' || t.status === 'blocked' || t.status === 'pending-tv';
});

out.push('');
out.push('## Waiting on you');
out.push('');
if (waiting.length) {
  waiting.forEach(function (t) {
    out.push('- **' + t.id + ' ' + t.title + '** — ' + reason(t.status));
  });
} else {
  out.push('Nothing. ');
}

out.push('');
out.push('## In flight');
out.push('');
var flight = tasks.filter(function (t) {
  return t.status === 'building' || t.status === 'review' || t.status === 'approved';
});
if (flight.length) {
  flight.forEach(function (t) {
    out.push('- **' + t.id + ' ' + t.title + '** — `' + t.status + '` on `' + t.branch + '`');
  });
} else {
  out.push('Nothing running.');
}

out.push('');

fs.writeFileSync(path.join(dir, 'BOARD.md'), out.join('\n'));
console.log('board: ' + tasks.length + ' task(s), ' + waiting.length + ' waiting on you');

// ---------------------------------------------------------------------

function field(text, key) {
  var m = new RegExp('^' + key + ':\\s*(.+)$', 'm').exec(text);
  return m ? m[1].trim() : null;
}

function title(text) {
  var m = /^#\s+(.+)$/m.exec(text);
  return m ? m[1].trim() : null;
}

function reason(status) {
  if (status === 'draft') return 'spec needs your approval before anyone starts';
  if (status === 'blocked') return 'two review rounds disagreed — needs your call';
  if (status === 'pending-tv') return 'code-complete; only the panel can prove it';
  return status;
}

function branches() {
  try {
    return execSync('git branch --list "crew/*" --format="%(refname:short)"',
                    { cwd: root, encoding: 'utf8' })
      .split('\n').map(function (s) { return s.trim(); }).filter(Boolean);
  } catch (e) { return []; }
}
