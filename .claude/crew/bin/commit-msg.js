#!/usr/bin/env node
// Enforces the commit convention. Called from .claude/crew/githooks/commit-msg,
// so it applies to every commit — human or agent — with no tokens spent.
'use strict';

var fs = require('fs');
var path = require('path');

var root = path.resolve(__dirname, '..', '..', '..');
var cfg = require(path.join(root, '.claude', 'crew.config.json')).commit;

var msgPath = process.argv[2];
if (!msgPath) {
  console.error('commit-msg: no message file given');
  process.exit(2);
}

var raw = fs.readFileSync(msgPath, 'utf8');
var lines = raw.split('\n').filter(function (l) { return l.indexOf('#') !== 0; });
var subject = (lines[0] || '').trim();

// Merges and reverts are generated by git; leave them alone.
if (/^(Merge|Revert)\b/.test(subject)) process.exit(0);

var errors = [];

// --- banned lines: attribution footers ---------------------------------
cfg.banned.forEach(function (needle) {
  if (raw.indexOf(needle) !== -1) {
    errors.push('remove "' + needle + '" — this project does not use commit attribution');
  }
});

// --- subject shape -----------------------------------------------------
var types = cfg.types.join('|');
var shape = new RegExp('^(' + types + ')(\\(([a-z0-9._-]+)\\))?(!)?: (.+)$');
var m = shape.exec(subject);

if (!m) {
  errors.push('subject must be "type(scope): summary"');
  errors.push('  types: ' + cfg.types.join(', '));
  errors.push('  got:   ' + (subject || '(empty)'));
} else {
  var scope = m[3];
  var summary = m[5];

  if (subject.length > cfg.subjectMax) {
    errors.push('subject is ' + subject.length + ' chars, max ' + cfg.subjectMax);
  }
  if (/\.$/.test(summary)) {
    errors.push('subject must not end with a full stop');
  }
  if (/^[A-Z][a-z]/.test(summary)) {
    errors.push('subject starts lowercase: "' + summary.charAt(0).toLowerCase() + summary.slice(1) + '"');
  }
  if (/^(added|adds|fixed|fixes|updated|updates|changed|changes|removed|removes|refactored)\b/i.test(summary)) {
    errors.push('subject must be imperative mood ("add", not "added"/"adds")');
  }
  if (cfg.requireScope && !scope) {
    errors.push('a scope is required: type(scope): summary');
  }
  if (scope) {
    var allowed = allowedScopes();
    if (allowed.indexOf(scope) === -1) {
      errors.push('unknown scope "' + scope + '"');
      errors.push('  allowed: ' + allowed.join(', '));
    }
  }
}

// --- body length -------------------------------------------------------
var body = lines.slice(1).join('\n').trim();
if (body) {
  if (lines[1] !== undefined && lines[1].trim() !== '') {
    errors.push('leave a blank line between the subject and the body');
  }
  var bodyLines = body.split('\n').filter(function (l) { return l.trim() !== ''; });
  if (bodyLines.length > cfg.bodyMaxLines) {
    errors.push('body is ' + bodyLines.length + ' lines, max ' + cfg.bodyMaxLines +
                ' — put the reasoning in the memory graph, not the commit');
  }
}

if (errors.length) {
  console.error('\ncommit rejected:\n');
  errors.forEach(function (e) { console.error('  ' + e); });
  console.error('\n  example: feat(player): play the next episode when one ends\n');
  process.exit(1);
}

// Scopes come from the source tree so the list maintains itself.
function allowedScopes() {
  var out = [];
  try {
    var dir = require(path.join(root, '.claude', 'crew.config.json')).scopes.fromDir;
    out = fs.readdirSync(path.join(root, dir))
      .filter(function (f) { return /\.js$/.test(f); })
      .map(function (f) { return f.replace(/\.js$/, ''); });
  } catch (e) { /* no source dir — extras only */ }
  var extra = require(path.join(root, '.claude', 'crew.config.json')).scopes.extra || [];
  return out.concat(extra).sort();
}
